import { MAX_SEQUENTIAL_THRESHOLD, computeGroupPoints, computeValidCurvePoints, computeScalarMultiplication } from "./logic.js";
import { coordFrequency, bitDistribution, avalancheTest } from "./stats.js";

const DEFAULT_BASE_POINT = {x: 1, y: 5};
const DEFAULT_PRIVATE_KEY = 6;

const validPoints = computeValidCurvePoints();
const gSelect = document.getElementById("g-select");

validPoints.forEach(({x, y}) => {
    const option = document.createElement("option");
    option.value = JSON.stringify({x, y});
    option.textContent = `(${x}, ${y})`;
    if (x === DEFAULT_BASE_POINT.x && y === DEFAULT_BASE_POINT.y) option.selected = true;
    gSelect.appendChild(option);
});

function validateInput(k, rawValue) {
    if (isNaN(k) || k < 1 || !Number.isInteger(parseFloat(rawValue))) {
        alert("Please enter a valid positive integer k > 0");
        return false;
    }
    return true;
}

let currentBasePoint = null;
let currentGroupPoints = null;
let currentAvalanche = null;

function computeStats(basePoint) {
    currentGroupPoints = computeGroupPoints(basePoint);
    currentAvalanche = avalancheTest(basePoint, currentGroupPoints.length + 1);
    const freq = coordFrequency(currentGroupPoints);
    const bits = bitDistribution(currentGroupPoints);

    ["group-output", "freq-output", "bits-output", "avalanche-output", "hash-output"]
        .forEach(id => document.getElementById(id).innerHTML = "");

    const groupOutput = document.getElementById("group-output");
    groupOutput.innerHTML = `<p>Subgroup generated by G: ${currentGroupPoints.length} affine points (group order = ${currentGroupPoints.length + 1}, including the point at infinity)</p>`;
    const pointsList = document.createElement("p");
    pointsList.textContent = currentGroupPoints.map(p => `(${p.x}, ${p.y})`).join("  ");
    groupOutput.appendChild(pointsList);

    const freqXText = Object.entries(freq.freqX)
        .map(([val, count]) => `x=${val}: ${count}`)
        .join(", ");
    const freqYText = Object.entries(freq.freqY)
        .map(([val, count]) => `y=${val}: ${count}`)
        .join(", ");
    document.getElementById("freq-output").innerHTML = `
        <p>X frequency: ${freqXText}</p>
        <p>Y frequency: ${freqYText}</p>
    `;

    document.getElementById("bits-output").innerHTML = `
        <p>Zeros: ${bits.zeros}</p>
        <p>Ones: ${bits.ones}</p>
        <p>Ones ratio: ${(bits.ratio * 100).toFixed(1)}%</p>
    `;

    const avalancheOutput = document.getElementById("avalanche-output");
    const validDiffs = currentAvalanche.diffs.filter(d => d.bitsChanged !== null);
    const avgBits = (validDiffs.reduce((acc, d) => acc + d.bitsChanged, 0) / validDiffs.length).toFixed(2);
    avalancheOutput.innerHTML = `<p>Average bits changed between consecutive keys: ${avgBits}</p>`;
    currentAvalanche.diffs.forEach(({k, bitsChanged}) => {
        const p = document.createElement("p");
        p.textContent = bitsChanged !== null
            ? `k=${k} → k=${k + 1}: ${bitsChanged} bit(s) changed`
            : `k=${k} → k=${k + 1}: point at infinity`;
        avalancheOutput.appendChild(p);
    });

    const hasAvalanche = parseFloat(avgBits) > 1.5;
    document.getElementById("hash-output").innerHTML = `
        <p>Deterministic: ✓</p>
        <p>One-way (ECDLP): ✓</p>
        <p>Avalanche behaviour: ${hasAvalanche ? "✓" : "✗"}</p>
        <p>Fixed-length output (like hash): ✗</p>
        <p>Collision resistance within group order: ✓</p>
    `;
}

function computeKey() {
    const rawValue = document.getElementById("k-input").value;
    const k = parseInt(rawValue);
    if (!validateInput(k, rawValue)) return;

    const basePoint = JSON.parse(document.getElementById("g-select").value);
    const { result, steps, fastMethodUsed } = computeScalarMultiplication(k, basePoint);

    ["steps-output", "result-output"]
        .forEach(id => document.getElementById(id).innerHTML = "");

    const stepsOutput = document.getElementById("steps-output");
    if (fastMethodUsed) {
        stepsOutput.innerHTML = `<p>Fast method (double-and-add) used for k=${k}</p>`;
        steps.forEach(({step, point}) => {
            const p = document.createElement("p");
            p.textContent = step === "..."
                ? "..."
                : `${step}G = ${point ? `(${point.x}, ${point.y})` : "point at infinity"}`;
            stepsOutput.appendChild(p);
        });
    } else {
        steps.forEach(({step, point}) => {
            const p = document.createElement("p");
            p.textContent = point
                ? `${step}G = (${point.x}, ${point.y})`
                : `${step}G = point at infinity`;
            stepsOutput.appendChild(p);
        });
    }

    document.getElementById("result-output").textContent = result
        ? `Public Key Q = ${k}G = (${result.x}, ${result.y})`
        : `${k}G = point at infinity`;
}

document.getElementById("compute-btn").addEventListener("click", computeKey);

document.getElementById("g-select").addEventListener("change", () => {
    const basePoint = JSON.parse(document.getElementById("g-select").value);
    if (!currentBasePoint || basePoint.x !== currentBasePoint.x || basePoint.y !== currentBasePoint.y) {
        currentBasePoint = basePoint;
        computeStats(basePoint);
    }
    computeKey();
});

document.getElementById("k-input").addEventListener("input", () => {
    const k = parseInt(document.getElementById("k-input").value);
    const input = document.getElementById("k-input");
    input.title = k > MAX_SEQUENTIAL_THRESHOLD
        ? `k > ${MAX_SEQUENTIAL_THRESHOLD}: fast method will be used, animation will show only first and last step`
        : "";
});

document.getElementById("k-input").value = DEFAULT_PRIVATE_KEY;
currentBasePoint = DEFAULT_BASE_POINT;
computeStats(DEFAULT_BASE_POINT);
computeKey();
